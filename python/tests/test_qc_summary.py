@pytest.fixture
def library(tmp_path, monkeypatch):
    """
    A ``qx_library`` the report can be built from, pointed at by ``QUNEXPATH``.

    CI checks the repository out with ``submodules: false`` and with no QuNex
    environment, so the real template is not there to be read and no test can
    assume it is. The stub carries the two placeholders the module substitutes
    into, which is the whole of the coupling between it and the page.
    """
    folder = tmp_path / "library" / "qx_library" / "data" / "scenes" / "qc"
    folder.mkdir(parents=True)
    (folder / qcr.TEMPLATE_NAME).write_text(
        "<html><script>/*PLOTLY*/</script>"
        "<script>const payload = /*DATA*/;</script></html>")
    (folder / qcr.PLOTLY_NAME).write_text("/* plotly stands in here */")
    monkeypatch.setenv("QUNEXPATH", str(tmp_path / "library"))
    return folder


@pytest.fixture
def no_pandas(monkeypatch):
    """
    Make ``import pandas`` and ``import scipy`` fail, as they do on the runner.

    ``.github/workflows/tests.yml`` installs neither, and dropping pandas from
    the report is one of the things this command was written for -- so the
    claim is worth holding to rather than trusting to the local environment,
    which has both.
    """
    blocked = ("pandas", "scipy")

    for name in list(sys.modules):
        if name.split(".")[0] in blocked:
            monkeypatch.delitem(sys.modules, name)

    class Absent(importlib.abc.MetaPathFinder):
        def find_spec(self, fullname, path=None, target=None):
            if fullname.split(".")[0] in blocked:
                raise ImportError(f"No module named '{fullname}'")
            return None

    monkeypatch.setattr(sys, "meta_path", [Absent()] + sys.meta_path)


def test_build_report_needs_no_pandas(tmp_path, library, no_pandas):
    html = qcr.build_report(SESSION_ROWS, RUN_ROWS, {"s01/bold1": {"fd": [0.1, 0.2]}},
                            _options(tmp_path / "sessions"))

    assert "/*DATA*/" not in html and "/*PLOTLY*/" not in html
    assert "plotly stands in here" in html

    payload = json.loads(html.split("const payload = ")[1].split(";</script>")[0])
    assert payload["subjects"] == ["s01", "s02", "s03"]
    assert "fs_surface_holes" in payload["metrics"]
    assert payload["stats"]["fs_surface_holes"]["median"] == 31.0
    assert payload["bold_runs"][0]["subject"] == "s01"
    assert payload["bold_traces"] == {"s01/bold1": {"fd": [0.1, 0.2]}}

    # `stages_missing` is the same for every session, so it carries nothing to
    # plot and the report says so rather than offering it as a parameter
    assert "stages_missing" not in payload["metrics"]


def test_a_missing_template_is_a_failure_and_is_named(study, tmp_path, monkeypatch):
    sinfo, sessionsfolder = study
    monkeypatch.setenv("QUNEXPATH", str(tmp_path / "empty"))

    log = run_qc_summary(sinfo, _options(sessionsfolder))

    assert log.status[2] == 1
    assert qcr.TEMPLATE_NAME in log.text
    assert "qx_library submodule" in log.text

    # the tables are what the command did manage, and they stay
    qcfolder = _qcfolder(sessionsfolder)
    assert os.path.isfile(os.path.join(qcfolder, "qc_summary.tsv"))
    assert not os.path.isfile(os.path.join(qcfolder, "qc_summary_report.html"))


def test_no_qunexpath_is_a_failure_that_says_what_to_do(study, monkeypatch):
    sinfo, sessionsfolder = study
    monkeypatch.delenv("QUNEXPATH", raising=False)

    log = run_qc_summary(sinfo, _options(sessionsfolder))

    assert log.status[2] == 1
    assert "QUNEXPATH is not set" in log.text
    assert "--qc_summary_report=no" in log.text
