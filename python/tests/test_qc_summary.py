"""
``run_qc_summary`` compiles what a study already holds, and says what it cannot.

The command's contract is unusual for a processing command, and these tests are
that contract: a session that has not reached a processing stage is *reported*
rather than dropped or raised on, and only being unable to build the report the
command was asked for counts as a failure. So most of what is checked here is
what happens when something is not there.

The movement fixture is written in the format ``compute_bold_stats`` writes
today -- a QuNex provenance block, and in a ``.scrub`` the parameters the
scrubbing was computed with, ahead of the header. That is the shape that broke
``mov_stats.read_named``, and the committed ``test_data/mov_stats`` fixtures do
not have it: they begin at the header line, which is why all 22 tests over them
passed while ``create_stats_report`` was failing on every real run.

The ``.scrub`` also flags one frame that the ``.bstats`` traces alone would not
justify. That is deliberate: the frames this command reports are the frames
preprocessing excluded, read out of the ``.scrub`` file rather than
re-thresholded from the traces, and a fixture where the two agree cannot tell
the two apart.
"""

