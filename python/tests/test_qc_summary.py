def test_the_bad_frames_are_the_ones_the_scrub_file_records(tmp_path):
    sessionsfolder = tmp_path / "sessions"
    sessionsfolder.mkdir()
    sinfo = [_session(str(sessionsfolder), "s01")]

    run_qc_summary(sinfo, _options(sessionsfolder, qc_summary_report="no"))

    qcfolder = _qcfolder(str(sessionsfolder))
    run = _rows(os.path.join(qcfolder, "qc_summary_bold.tsv"))[0]

    assert run["flags"] == "pipeline"
    assert int(run["n_bad"]) == len(SCRUB_BAD)
    assert int(run["frames_retained"]) == len(FD) - len(SCRUB_BAD)
    assert run["fdt"] == "0.5" and run["dvarsmet"] == "1.5"

    # and the traces carry the same mask, so the report plots what the table counts
    with open(os.path.join(qcfolder, "qc_summary_bold_traces.json")) as traces:
        trace = json.load(traces)["s01/bold1"]
    assert {frame for frame, bad in enumerate(trace["bad"], 1) if bad} == SCRUB_BAD


def test_an_explicit_threshold_recomputes_the_flags_and_says_so(tmp_path):
    sessionsfolder = tmp_path / "sessions"
    sessionsfolder.mkdir()
    sinfo = [_session(str(sessionsfolder), "s01")]

    # a threshold the run was not processed with is the one case the flags are
    # rebuilt from the traces, and the row has to say that they were
    run_qc_summary(sinfo, _options(sessionsfolder, mov_fd="0.7",
                                   qc_summary_report="no"))

    run = _rows(os.path.join(_qcfolder(str(sessionsfolder)),
                             "qc_summary_bold.tsv"))[0]
    assert run["flags"] == "recomputed"
    assert int(run["n_bad"]) == len(TRACE_BAD)
    assert run["fdt"] == "0.7"


