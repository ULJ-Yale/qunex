def test_the_tables_carry_the_declared_headers(study):
    sinfo, sessionsfolder = study
    run_qc_summary(sinfo, _options(sessionsfolder, qc_summary_report="no"))

    qcfolder = _qcfolder(sessionsfolder)
    with open(os.path.join(qcfolder, "qc_summary.tsv"), newline="") as tsv:
        header = next(csv.reader(tsv, delimiter="\t"))

    # a column no session in the study has a value for is left out entirely,
    # so the header is the declared order narrowed rather than reordered
    assert header[0] == "session"
    assert header == [name for name in SESSION_COLUMNS if name in header]
    for name in ("fs_surface_holes", "completeness", "stages_missing",
                 "likely_failure_step"):
        assert name in header

    with open(os.path.join(qcfolder, "qc_summary_bold.tsv"), newline="") as tsv:
        assert next(csv.reader(tsv, delimiter="\t")) == qcb.RUN_COLUMNS


