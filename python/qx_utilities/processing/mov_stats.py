"""
Movement and BOLD statistics reporting for ``create_stats_report``.

This replaces ``r/qx_utilities/bold_stats.R``. It reads the per-BOLD movement
correction parameters, the scrubbing flags and the image statistics that
``compute_bold_stats`` leaves in ``images/functional/movement``, appends the
group level reports, writes the per-BOLD fidl scrubbing snippets, and draws the
three movement plots.

It computes no scrubbing of its own. Which frames are bad is decided by
``img_compute_scrub.m`` and read back out of the ``.scrub`` file, exactly as the
R script did -- the two names that select a column, ``mov_fidl`` and
``mov_post``, are therefore ``.scrub`` column names and nothing else.

The module registers no command. ``create_stats_report`` in ``workflow.py`` owns
the option surface, the ``--test`` contract and the log; this is the work behind
it, and it is called only from there.
"""

